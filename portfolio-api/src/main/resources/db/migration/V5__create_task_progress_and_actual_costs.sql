CREATE TABLE task_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    report_date DATE NOT NULL,
    completion_percent NUMERIC(5, 2) NOT NULL,

    CONSTRAINT fk_task_progress_task FOREIGN KEY (task_id) REFERENCES tasks(id),

    CONSTRAINT chk_task_progress_percent CHECK (completion_percent BETWEEN 0 AND 100),

    CONSTRAINT uq_task_progress_task_date UNIQUE (task_id, report_date)
);

CREATE TABLE actual_costs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    cost_date DATE NOT NULL,
    amount NUMERIC(15, 2) NOT NULL,
    description TEXT,

    CONSTRAINT fk_actual_costs_task FOREIGN KEY (task_id) REFERENCES tasks(id),

    CONSTRAINT chk_actual_costs_amount CHECK (amount >= 0)
);

CREATE INDEX idx_task_progress_report_date ON task_progress(report_date);

CREATE INDEX idx_actual_costs_task_date ON actual_costs(task_id, cost_date);
