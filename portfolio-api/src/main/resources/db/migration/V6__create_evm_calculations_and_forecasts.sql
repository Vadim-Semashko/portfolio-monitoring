CREATE TABLE earned_value_calculations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    report_date DATE NOT NULL,

    pv NUMERIC(15, 2) NOT NULL,
    ev NUMERIC(15, 2) NOT NULL,
    ac NUMERIC(15, 2) NOT NULL,
    cv NUMERIC(15, 2) NOT NULL,
    sv NUMERIC(15, 2) NOT NULL,

    cpi NUMERIC(12, 4),
    spi NUMERIC(12, 4),

    CONSTRAINT fk_evm_project FOREIGN KEY (project_id) REFERENCES projects(id),

    CONSTRAINT uq_evm_project_date UNIQUE (project_id, report_date),

    CONSTRAINT chk_evm_values CHECK (pv >= 0 AND ev >= 0 AND ac >= 0),
    CONSTRAINT chk_evm_indices CHECK ((cpi IS NULL OR cpi >= 0) AND (spi IS NULL OR spi >= 0))
);

CREATE TABLE forecasts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calculation_id BIGINT NOT NULL UNIQUE,

    eac NUMERIC(15, 2),
    estimated_duration INTEGER,
    estimated_end_date DATE,

    CONSTRAINT fk_forecasts_calculation FOREIGN KEY (calculation_id)REFERENCES earned_value_calculations(id),

    CONSTRAINT chk_forecast_eac CHECK (eac IS NULL OR eac >= 0),
    CONSTRAINT chk_forecast_duration CHECK (estimated_duration IS NULL OR estimated_duration >= 0)
);

CREATE INDEX idx_evm_project_date ON earned_value_calculations(project_id, report_date);
