CREATE TABLE portfolios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manager_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_portfolios_manager FOREIGN KEY (manager_id) REFERENCES users(id)
);

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL,
    manager_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PLANNED',

    CONSTRAINT fk_projects_portfolio FOREIGN KEY (portfolio_id) REFERENCES portfolios(id),
    CONSTRAINT fk_projects_manager FOREIGN KEY (manager_id) REFERENCES users(id),

    CONSTRAINT chk_projects_dates CHECK (end_date >= start_date),
    CONSTRAINT chk_projects_status CHECK (status IN ('PLANNED','IN_PROGRESS', 'COMPLETED','CANCELLED'))
);

CREATE INDEX idx_portfolios_manager_id ON portfolios(manager_id);
CREATE INDEX idx_projects_portfolio_id ON projects(portfolio_id);
CREATE INDEX idx_projects_manager_id ON projects(manager_id);
