CREATE TABLE project_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL UNIQUE,
    budget NUMERIC(15, 2) NOT NULL DEFAULT 0,
    planned_start_date DATE NOT NULL,
    planned_end_date DATE NOT NULL,

    CONSTRAINT fk_project_plans_project FOREIGN KEY (project_id) REFERENCES projects(id),

    CONSTRAINT chk_project_plans_budget CHECK (budget >= 0),
    CONSTRAINT chk_project_plans_dates CHECK (planned_end_date >= planned_start_date)
);

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    planned_start_date DATE NOT NULL,
    planned_end_date DATE NOT NULL,
    planned_cost NUMERIC(15, 2) NOT NULL,

    CONSTRAINT fk_tasks_plan FOREIGN KEY (plan_id) REFERENCES project_plans(id),

    CONSTRAINT chk_tasks_cost CHECK (planned_cost >= 0),
    CONSTRAINT chk_tasks_dates CHECK (planned_end_date >= planned_start_date)
);

CREATE INDEX idx_tasks_plan_id ON tasks(plan_id);
